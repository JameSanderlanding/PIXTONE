package com.vova.glyph.i18n

import android.util.LruCache

internal fun translate(text: String, language: AppLanguage): String {
    DICT[text]?.let { return it.of(language) }
    ruleCache.get(text)?.let { return it }
    for (rule in RULES) {
        val match = rule.regex.matchEntire(text) ?: continue
        return rule.apply(language, match).also { ruleCache.put(text, it) }
    }
    ruleCache.put(text, text)
    return text
}

internal fun clearTranslationCache() {
    ruleCache.evictAll()
}

private val ruleCache = LruCache<String, String>(RULE_CACHE_SIZE)

private const val RULE_CACHE_SIZE = 512

private data class Tr(
    val en: String,
    val de: String,
    val fr: String,
    val zh: String,
    val ja: String,
) {
    fun of(language: AppLanguage): String = when (language) {
        AppLanguage.EN -> en
        AppLanguage.DE -> de
        AppLanguage.FR -> fr
        AppLanguage.ZH -> zh
        AppLanguage.JA -> ja
        AppLanguage.RU -> ""
    }
}

private fun t(en: String, de: String, fr: String, zh: String, ja: String) =
    Tr(en, de, fr, zh, ja)

private class Rule(
    val regex: Regex,
    val en: String,
    val de: String,
    val fr: String,
    val zh: String,
    val ja: String,
) {
    fun apply(language: AppLanguage, match: MatchResult): String {
        val format = when (language) {
            AppLanguage.EN -> en
            AppLanguage.DE -> de
            AppLanguage.FR -> fr
            AppLanguage.ZH -> zh
            AppLanguage.JA -> ja
            AppLanguage.RU -> return match.value
        }
        var result = format
        for (index in 1 until match.groupValues.size) {
            result = result.replace("%$index", match.groupValues[index])
        }
        return result
    }
}

private fun r(
    pattern: String,
    en: String,
    de: String,
    fr: String,
    zh: String,
    ja: String,
) = Rule(Regex(pattern), en, de, fr, zh, ja)

